from reportlab.lib.pagesizes import letter, A4
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import SimpleDocTemplate, Table, TableStyle, Paragraph, Spacer, Image
from reportlab.lib.units import inch
from pathlib import Path
from datetime import datetime
from typing import Dict


def generate_analysis_report(
    analysis_data: Dict,
    output_path: Path,
    patient_name: str = "Unknown"
) -> Path:
    """
    Generate PDF report for analysis
    
    Args:
        analysis_data: Dictionary with analysis results
        output_path: Where to save PDF
        patient_name: Patient name
    """
    doc = SimpleDocTemplate(str(output_path), pagesize=A4)
    story = []
    styles = getSampleStyleSheet()
    
    # Title
    title_style = ParagraphStyle(
        'CustomTitle',
        parent=styles['Heading1'],
        fontSize=24,
        textColor=colors.HexColor('#1E40AF'),
        spaceAfter=30,
        alignment=1  # Center
    )
    
    title = Paragraph("RadiSense AI - Analysis Report", title_style)
    story.append(title)
    story.append(Spacer(1, 0.3*inch))
    
    # Patient info
    info_style = styles['Normal']
    info_data = [
        ["Patient:", patient_name],
        ["Analysis ID:", analysis_data.get('analysis_id', 'N/A')],
        ["Date:", datetime.now().strftime("%Y-%m-%d %H:%M:%S")],
        ["Model:", analysis_data.get('model_used', 'DenseNet-121')],
        ["Confidence:", f"{analysis_data.get('confidence_score', 0):.2%}"]
    ]
    
    info_table = Table(info_data, colWidths=[2*inch, 4*inch])
    info_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (0, -1), colors.HexColor('#E5E7EB')),
        ('TEXTCOLOR', (0, 0), (-1, -1), colors.black),
        ('ALIGN', (0, 0), (-1, -1), 'LEFT'),
        ('FONTNAME', (0, 0), (0, -1), 'Helvetica-Bold'),
        ('FONTSIZE', (0, 0), (-1, -1), 10),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 12),
        ('GRID', (0, 0), (-1, -1), 1, colors.grey)
    ]))
    
    story.append(info_table)
    story.append(Spacer(1, 0.5*inch))
    
    # Results title
    results_title = Paragraph("Pathology Detection Results", styles['Heading2'])
    story.append(results_title)
    story.append(Spacer(1, 0.2*inch))
    
    # Predictions table
    predictions = analysis_data.get('predictions', {})
    pred_data = [['Pathology', 'Probability', 'Status']]
    
    for pathology, prob in predictions.items():
        status = "POSITIVE" if prob > 0.5 else "NEGATIVE"
        color = colors.red if prob > 0.5 else colors.green
        pred_data.append([
            pathology,
            f"{prob:.2%}",
            status
        ])
    
    pred_table = Table(pred_data, colWidths=[3*inch, 1.5*inch, 1.5*inch])
    pred_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#3B82F6')),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.whitesmoke),
        ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
        ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
        ('FONTSIZE', (0, 0), (-1, 0), 12),
        ('BOTTOMPADDING', (0, 0), (-1, 0), 12),
        ('BACKGROUND', (0, 1), (-1, -1), colors.beige),
        ('GRID', (0, 0), (-1, -1), 1, colors.grey)
    ]))
    
    story.append(pred_table)
    story.append(Spacer(1, 0.5*inch))
    
    # Footer
    footer = Paragraph(
        "This report is generated by RadiSense AI. "
        "Please consult with a medical professional for final diagnosis.",
        styles['Italic']
    )
    story.append(footer)
    
    # Build PDF
    doc.build(story)
    
    return output_path